// Language picker: fills any element with data-lang-picker
(function () {
  function mount(slot) {
    var I = window.SITE_I18N, codes = Object.keys(I.langs);
    slot.innerHTML = '<button type="button" class="lang-btn notr" aria-haspopup="true" aria-expanded="false" aria-label="Language"><span aria-hidden="true">🌐</span> <b></b></button><ul class="lang-menu notr" hidden role="menu"></ul>';
    var btn = slot.querySelector('.lang-btn'), menu = slot.querySelector('.lang-menu');
    function draw() {
      btn.querySelector('b').textContent = I.lang.toUpperCase();
      menu.innerHTML = codes.map(function (c) { return '<li role="none"><button type="button" role="menuitemradio" aria-checked="' + (c === I.lang) + '" data-l="' + c + '">' + I.langs[c].name + '</button></li>'; }).join('');
    }
    function open(v) { menu.hidden = !v; btn.setAttribute('aria-expanded', v); }
    btn.addEventListener('click', function (e) { e.stopPropagation(); open(menu.hidden); });
    menu.addEventListener('click', function (e) { var b = e.target.closest('[data-l]'); if (!b) return; I.set(b.dataset.l); draw(); open(false); });
    document.addEventListener('click', function () { open(false); });
    document.addEventListener('keydown', function (e) { if (e.key === 'Escape') open(false); });
    draw();
  }
  function go() { document.querySelectorAll('[data-lang-picker]').forEach(mount); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', go); else go();
})();
